"""Validate explicit runtime rules and emit typed C# metadata."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def generate(root=ROOT, check=False):
    pool = json.loads((root / 'data/card-pool.json').read_text(encoding='utf-8-sig'))
    cards = {card['id']: card for card in pool['cards'] + pool['retiredCards']}
    data = json.loads((root / 'data/card-rules.json').read_text(encoding='utf-8-sig'))
    if data['format'] != 1:
        raise ValueError('Unsupported card rule format')
    rules = data['cards']
    missing = set(cards) - set(rules)
    if missing:
        raise ValueError('Missing runtime rules: ' + ', '.join(sorted(missing)))
    definitions = (root / 'src/Models/CardRules.cs').read_text(encoding='utf-8')
    enums = {name: set(re.findall(r'\b\w+\b', body)) for name, body in
             re.findall(r'internal enum (\w+)\s*\{([^}]+)\}', definitions, re.S)}
    def member(enum, value):
        if value not in enums[enum]:
            raise ValueError(f'Unknown {enum}: {value}')
        return enum + '.' + value
    def quoted(value):
        return json.dumps(value, ensure_ascii=False)
    lines = ['// Generated by tools/assets/generate-card-rules.py.',
             'namespace ShoujoKagekiJunna.Models;', '', 'internal static partial class CardRules', '{',
             '    private static readonly Dictionary<string, CardRuleDefinition> Definitions = new()', '    {']
    for key, rule in sorted(rules.items()):
        if key not in cards and not rule.get('legacy'):
            raise ValueError(f'Unknown card rule {key}')
        allowed = {'fields', 'tips', 'upgradedTips', 'effect', 'power', 'relatedCards', 'legacy'}
        if set(rule) - allowed:
            raise ValueError(f'Unknown properties for {key}')
        lines += ['        [' + quoted(key) + '] = new()', '        {']
        fields = rule.get('fields', {})
        if fields:
            if key in cards:
                saved_fields = {value['name'] for value in cards[key]['values']}
                if set(fields.values()) - saved_fields:
                    raise ValueError(f'Unknown saved field for {key}')
            lines += ['            Fields = new Dictionary<string, string>', '            {']
            lines += ['                [' + quoted(name) + '] = ' + quoted(field) + ','
                      for name, field in sorted(fields.items())]
            lines += ['            },']
        for source, target in [('tips', 'Tips'), ('upgradedTips', 'UpgradedTips')]:
            values = rule.get(source, [])
            if len(values) != len(set(values)):
                raise ValueError(f'Duplicate {source} for {key}')
            if values:
                lines += ['            ' + target + ' = [' + ', '.join(member('CardTip', value) for value in values) + '],']
        if 'effect' in rule:
            lines += ['            Effect = ' + member('SimpleCardEffect', rule['effect']) + ',']
        if 'relatedCards' in rule:
            if set(rule['relatedCards']) - set(cards):
                raise ValueError(f'Unknown card reference for {key}')
            lines += ['            RelatedCards = [' + ', '.join(quoted(value) for value in rule['relatedCards']) + '],']
        if 'power' in rule:
            power = rule['power']
            lines += ['            PowerDescription = ' + member('PowerDescriptionKind', power['description']) + ',',
                      '            PowerAmount = ' + member('PowerAmountKind', power['amount']) + ',',
                      '            SinglePower = ' + str(power['single']).lower() + ',']
        lines += ['        },']
    powers = set(re.findall(r'CatalogPower\("([^"]+)"\)',
                 (root / 'src/Models/CatalogPowers.Generated.cs').read_text(encoding='utf-8')))
    if any('power' not in rules.get(key, {}) for key in powers):
        raise ValueError('Every catalog power needs an explicit display rule')
    lines += ['    };', '}', '']
    output = '\n'.join(lines)
    path = root / 'src/Models/CardRules.Generated.cs'
    if check:
        if not path.exists() or path.read_text(encoding='utf-8') != output:
            raise ValueError('Generated card rules are out of date')
    else:
        path.write_text(output, encoding='utf-8')
    print(f'Validated {len(rules)} card rules, {len(powers)} power rules and saved field identities.')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    generate(check=parser.parse_args().check)
