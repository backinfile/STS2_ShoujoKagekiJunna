    internal static string Resolve(string id, string name) => Bindings.GetValueOrDefault((id, name), name);
    internal static void Validate(CardDefinition card)
    {
        foreach (var binding in Bindings.Where(pair => pair.Key.Id == card.Id))
            if (!card.Values.Any(value => value.Name == binding.Value))
                throw new InvalidDataException($"Card {card.Id} has no field {binding.Value} for {binding.Key.Name}.");
    }
